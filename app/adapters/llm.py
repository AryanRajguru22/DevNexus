"""LLM provider interface and the deterministic mock (no network, no paid service).

LABEL: MockLLMProvider returns templated code. It is NOT a real language model; the UI and docs say so.
"""
from __future__ import annotations

import re
from collections.abc import Callable
from dataclasses import dataclass
from typing import Protocol

from .markers import FAIL_LLM, FAIL_LLM_ALWAYS, injected


class LLMUnavailable(Exception):
    """The LLM service is unavailable, slow or rate limited (risk R3)."""


@dataclass(frozen=True)
class CodeRequest:
    title: str
    description: str
    requirement: str
    feedback: str | None
    attempt: int  # 1-based generation attempt for this task
    max_loc: int


@dataclass(frozen=True)
class GeneratedCode:
    files: dict[str, str]
    summary: str


class LLMProvider(Protocol):
    name: str

    def generate(self, request: CodeRequest) -> GeneratedCode: ...


class UnknownProviderError(ValueError):
    """DEVNEXUS_LLM_PROVIDER names a provider that is not registered."""


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:40] or "task"
    return f"t_{slug}" if slug[0].isdigit() else slug


def _one_line(text: str, limit: int) -> str:
    cleaned = re.sub(r"\s+", " ", text).replace('"""', "'''").replace("\\", "/").strip()
    return cleaned[:limit]


class MockLLMProvider:
    name = "mock-llm (deterministic template, not a real model)"

    def generate(self, request: CodeRequest) -> GeneratedCode:
        if injected(f"{request.title} {request.description}", FAIL_LLM, FAIL_LLM_ALWAYS, request.attempt):
            raise LLMUnavailable("Simulated LLM outage: the language-model service did not respond")
        slug = slugify(request.title)
        title = _one_line(request.title, 100)
        safe_title = title.replace('"', "'")
        lines = [
            f'"""{title}',
            "",
            f"Generated by MockLLMProvider (attempt {request.attempt}); template output, not a real model.",
            f"Requirement: {_one_line(request.requirement, 160)}",
            '"""',
            "from __future__ import annotations",
            "",
            "from typing import Any",
        ]
        if request.feedback:
            lines.append(f"# Rework feedback applied (attempt {request.attempt}): {_one_line(request.feedback, 120)}")
        lines += [
            "",
            "",
            f"def validate_{slug}(payload: dict[str, Any]) -> list[str]:",
            '    """Return the validation problems found in the payload."""',
            "    problems: list[str] = []",
            "    if not isinstance(payload, dict) or not payload:",
            '        problems.append("payload must be a non-empty object")',
            "    return problems",
            "",
            "",
            f"def handle_{slug}(payload: dict[str, Any]) -> dict[str, Any]:",
            '    """Process the payload and return a response document."""',
            f"    problems = validate_{slug}(payload)",
            "    if problems:",
            '        return {"ok": False, "errors": problems}',
            f'    return {{"ok": True, "task": "{safe_title}", "received": sorted(payload)}}',
            "",
        ]
        return GeneratedCode(
            files={f"generated/{slug}.py": "\n".join(lines)},
            summary=f"Generated generated/{slug}.py ({len(lines)} lines) from the task description",
        )


def _ollama() -> LLMProvider:
    from .ollama import OllamaLLMProvider  # imported lazily: ollama.py imports names from this module

    return OllamaLLMProvider.from_environment()


# Extension point: a provider is added by registering a zero-argument factory here (it must read its own settings
# from the environment). "mock" is the default and needs nothing; "ollama" talks to a local Ollama server and is
# optional. No paid service or API key is needed to run or test DevNexus.
PROVIDERS: dict[str, Callable[[], LLMProvider]] = {"mock": MockLLMProvider, "ollama": _ollama}


def create_provider(name: str) -> LLMProvider:
    try:
        return PROVIDERS[name]()
    except KeyError:
        raise UnknownProviderError(
            f"Unknown LLM provider '{name}'. Set DEVNEXUS_LLM_PROVIDER to one of: {', '.join(sorted(PROVIDERS))}"
        ) from None
