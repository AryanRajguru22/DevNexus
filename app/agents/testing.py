"""Testing Agent (FR-8).

SAFETY / LABEL: the generated code is parsed with ast and inspected statically. It is NEVER imported or executed,
so a faulty or malicious generation cannot harm the host. Results are therefore *simulated* test outcomes and the
`coverage_pct` is the share of generated functions whose generated checks pass - not real line coverage.
"""
from __future__ import annotations

import ast
from dataclasses import dataclass

from ..adapters.git_local import LocalGitAdapter
from ..adapters.markers import FAIL_TESTS, FAIL_TESTS_ALWAYS, injected
from ..enums import AgentType


@dataclass(frozen=True)
class TestingOutcome:
    __test__ = False  # not a pytest class

    passed: int
    failed: int
    coverage_pct: float
    report: str


class TestingAgent:
    __test__ = False  # not a pytest class
    agent_type = AgentType.TESTING

    def __init__(self, git: LocalGitAdapter):
        self.git = git

    def run(self, *, project_id: int, branch: str, hints: str, attempt: int) -> TestingOutcome:
        sources = {
            path: text
            for path, text in self.git.read_branch(project_id, branch).items()
            if path.endswith(".py") and not path.startswith("tests/")
        }
        problems: list[str] = []
        generated_tests: dict[str, str] = {}
        total_functions = 0
        failing_functions: set[str] = set()
        passed = failed = 0

        for path, source in sources.items():
            module = path.removesuffix(".py").replace("/", ".")
            try:
                tree = ast.parse(source)  # parse only - never executed
            except SyntaxError as exc:
                problems.append(f"{path}: syntax error on line {exc.lineno}: {exc.msg}")
                failed += 1
                continue
            names = []
            for node in ast.walk(tree):
                if not isinstance(node, ast.FunctionDef):
                    continue
                names.append(node.name)
                total_functions += 1
                # Two generated static checks per function.
                for ok, label in (
                    (ast.get_docstring(node) is not None, "has a docstring"),
                    (node.returns is not None, "declares a return type"),
                ):
                    if ok:
                        passed += 1
                    else:
                        failed += 1
                        failing_functions.add(f"{module}.{node.name}")
                        problems.append(f"{module}.{node.name} {label}: FAILED")
            generated_tests[f"tests/test_{path.removeprefix('generated/')}"] = self._render_tests(module, names)

        if not sources:
            failed += 1
            problems.append("no source files found on the branch")
        if injected(hints, FAIL_TESTS, FAIL_TESTS_ALWAYS, attempt):
            failed += 1
            problems.append("injected failure (demo marker): test_expected_behaviour FAILED")
        if generated_tests:
            self.git.commit(project_id, branch, generated_tests, "Add generated tests")

        covered = total_functions - len(failing_functions)
        coverage = round(100.0 * covered / total_functions, 1) if total_functions else 0.0
        report = f"{passed} passed, {failed} failed (simulated static checks; generated code was not executed)"
        report += "".join(f"\n- {p}" for p in problems)
        return TestingOutcome(passed=passed, failed=failed, coverage_pct=coverage, report=report)

    @staticmethod
    def _render_tests(module: str, names: list[str]) -> str:
        lines = ["# Generated by the Testing Agent. Static template; not executed by DevNexus.", ""]
        lines += [f"from {module} import {name}" for name in names]
        for name in names:
            lines += ["", "", f"def test_{name}_is_documented():", f"    assert {name}.__doc__"]
        return "\n".join(lines) + "\n"
